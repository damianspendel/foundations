#!/usr/bin/env python3
"""Generate the student problem files from the worked solutions.

    python3 scripts/make_exercises.py            # write Exercises/Problems/<Part>.lean
    python3 scripts/make_exercises.py --check    # fail if a Problems file is missing or stale
    python3 scripts/make_exercises.py --lean     # also elaborate each Problems file (lake env lean)

Marker scheme (used in Exercises/Solutions/<Part>.lean):

    theorem foo ... := by
      -- SOLUTION
      <proof lines>
      -- END

A line consisting only of `-- SOLUTION` opens a block and the next line consisting only of
`-- END` closes it. The whole block, markers included, is replaced by one line `sorry`
indented like the `-- SOLUTION` marker. Everything outside the blocks (imports, docstrings
with statements and hints, the theorem statements themselves) is copied verbatim. Blocks
cannot be nested, every block must be closed, and the line before a block must end in `:= by`
so that the replacement `sorry` is a tactic proof. Every `theorem` in a solution file must
have exactly one block, so that no worked proof leaks into the student version.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOLUTIONS = ROOT / "Exercises" / "Solutions"
PROBLEMS = ROOT / "Exercises" / "Problems"

OPEN, CLOSE = "-- SOLUTION", "-- END"
THEOREM = re.compile(r"^\s*(private\s+|protected\s+)*theorem\b")


class MarkerError(Exception):
    pass


def strip_solutions(src: str, name: str) -> str:
    out, inside, blocks, theorems = [], False, 0, 0
    lines = src.splitlines()
    for i, line in enumerate(lines, 1):
        s = line.strip()
        if THEOREM.match(line):
            theorems += 1
        if s == OPEN:
            if inside:
                raise MarkerError(f"{name}:{i}: nested {OPEN}")
            prev = next((l for l in reversed(out) if l.strip()), "")
            if not prev.rstrip().endswith(":= by"):
                raise MarkerError(f"{name}:{i}: {OPEN} must follow a line ending in ':= by'")
            inside, blocks = True, blocks + 1
            out.append(line[: len(line) - len(line.lstrip())] + "sorry")
        elif s == CLOSE:
            if not inside:
                raise MarkerError(f"{name}:{i}: {CLOSE} without {OPEN}")
            inside = False
        elif not inside:
            out.append(line)
    if inside:
        raise MarkerError(f"{name}: unclosed {OPEN}")
    if blocks != theorems:
        raise MarkerError(f"{name}: {theorems} theorems but {blocks} {OPEN} blocks")
    banner = (f"-- GENERATED by scripts/make_exercises.py from Exercises/Solutions/{name}.\n"
              f"-- Do not edit: replace each `sorry` with your proof, or edit the solution file\n"
              f"-- and regenerate. See EXERCISES.md.\n")
    return banner + "\n".join(out) + "\n"


def main(argv):
    check, run_lean = "--check" in argv, "--lean" in argv
    PROBLEMS.mkdir(parents=True, exist_ok=True)
    stale, failed = [], []
    for sol in sorted(SOLUTIONS.glob("*.lean")):
        try:
            text = strip_solutions(sol.read_text(), sol.name)
        except MarkerError as e:
            print("error:", e)
            return 1
        target = PROBLEMS / sol.name
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(target.relative_to(ROOT))
        else:
            target.write_text(text)
            holes = sum(l.strip() == "sorry" for l in text.splitlines())
            print(f"wrote {target.relative_to(ROOT)}  ({holes} exercises)")
        if run_lean:
            r = subprocess.run(["lake", "env", "lean", str(target.relative_to(ROOT))],
                               cwd=ROOT, capture_output=True, text=True)
            msgs = (r.stdout + r.stderr).splitlines()
            errors = [m for m in msgs if ": error" in m]
            if r.returncode != 0 or errors:
                failed.append(target.relative_to(ROOT))
                print("\n".join(errors or msgs))
            else:
                warns = sum("declaration uses" in m and "sorry" in m for m in msgs)
                print(f"  elaborates: {target.relative_to(ROOT)} ({warns} sorry warnings)")
    if stale:
        print("stale or missing (run scripts/make_exercises.py):", *map(str, stale))
        return 1
    if failed:
        print("failed to elaborate:", *map(str, failed))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
